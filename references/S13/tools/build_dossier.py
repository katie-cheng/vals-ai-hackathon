"""Render inputs/dossier/DOSSIER-generated.md from live-capture.json and the live-app source."""
import json, pathlib, re
HERE = pathlib.Path(__file__).resolve().parents[1]
cap = json.loads((HERE / "inputs/dossier/live-capture.json").read_text())
src = HERE / "inputs/live-app/src"
md = ["# S13 live-app capture (generated)", "", "Generated by `tools/build_dossier.py` from `live-capture.json` (Playwright run against https://suds-squad-immersive-ann4.arcada.app) and the decompiled source in `inputs/live-app/src`.", "",
      "## Header behaviour by viewport", "", "| Width | Desktop nav | Menu button | Nav height (px) | Doc width |", "| --- | --- | --- | --- | --- |"]
for w, e in cap.items():
    h = e["header"]; md.append(f"| {w} | {h['nav']} | {h['menuButton']} | {h['navHeight']} | {h['docWidth']} |")
md += ["", "A nav height above ~36px means the links wrapped onto two lines (critique #51).", ""]
for w in ("1440", "390"):
    md += [f"## Sections at {w}px", "", "| Section | Top | Height | Background | Components | Top fonts (family weight: count) | Top font sizes | Top radii |", "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    for s in cap[w]["sections"]:
        name = s["id"] or s["tag"]
        f = ", ".join(f"{a}: {b}" for a, b in s["fonts"][:4]); z = ", ".join(a for a, _ in s["sizes"][:5])
        r = ", ".join(("pill" if a.startswith("3.35") else a) for a, _ in s["radii"][:3])
        md.append(f"| {name} | {s['top']} | {s['height']} | {s['bg']} | {' '.join(c.split('/')[-1] for c in s['components'])} | {f} | {z} | {r} |")
    md.append("")
md += ["## Animation inventory (from source)", "", "| File | Scroll-linked (`useScroll`/`useTransform`) | In-view entrances (`whileInView`/`Reveal`/`SplitWords`) | Hover (`whileHover`, `group-hover:`, `hover:`) | CSS keyframe classes | Canvas / rAF |", "| --- | --- | --- | --- | --- | --- |"]
for p in sorted(src.rglob("*.tsx")):
    t = p.read_text()
    kf = sorted(set(re.findall(r"\banimate-[a-z-]+", t)))
    md.append(f"| {p.relative_to(src)} | {t.count('useTransform(')} | {t.count('whileInView') + t.count('<Reveal') + t.count('<SplitWords')} | {t.count('whileHover') + t.count('group-hover:') + t.count('hover:')} | {' '.join(kf)} | {'yes' if 'requestAnimationFrame' in t else ''} |")
md += ["", "## Copy, verbatim (innerText at 1440px)", ""]
for s in cap["1440"]["sections"]:
    md += [f"### {s['id'] or s['tag']}", "", "```text", s["text"], "```", ""]
(HERE / "inputs/dossier/DOSSIER-generated.md").write_text("\n".join(md))
