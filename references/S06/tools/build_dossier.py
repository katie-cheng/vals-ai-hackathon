"""Render inputs/dossier/DOSSIER-generated.md from live-capture.json and the decompiled source."""
import json, pathlib, re
HERE = pathlib.Path(__file__).resolve().parents[1]
cap = json.loads((HERE / "inputs/dossier/live-capture.json").read_text())
src = HERE / "inputs/live-app/src"
md = ["# S06 live-app capture (generated)", "", "Generated by `tools/build_dossier.py` from `live-capture.json` (Playwright run against https://rocksteady-campus-oj1m.arcada.app) and the decompiled source in `inputs/live-app/src`.", "",
      "## Header behaviour by viewport (home page)", "", "| Width | Desktop nav | Menu button | 'Order now' button | Bottom tab bar | Header height (px) | Doc width |", "| --- | --- | --- | --- | --- | --- | --- |"]
yn = lambda v: "visible" if v else "hidden"
for w, h in cap["header"].items():
    md.append(f"| {w} | {yn(h['nav'])} | {yn(h['menuButton'])} | {yn(h['orderNow'])} | {yn(h['bottomNav'])} | {h['headerHeight']:.0f} | {h['docWidth']} |")
md += ["", "Below 768px the header's 'Order now' button is hidden and only the bag icon stays (the pattern S05 #289 describes).", ""]
for route, by_w in cap["routes"].items():
    for w in ("1440", "390"):
        md += [f"## `{route}` at {w}px", "", "| Section | Top | Height | Background | Components | Top fonts (family weight: count) | Top font sizes | Top radii | Small uppercase / text nodes | Under 12px | Icons |", "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
        for s in by_w[w]:
            name = (s["id"] or s["heading"] or s["tag"]).replace("\n", " ")[:40]
            f = ", ".join(f"{a}: {b}" for a, b in s["fonts"][:4]); z = ", ".join(a for a, _ in s["sizes"][:5])
            r = ", ".join(("pill" if a.startswith("3.4") or a.startswith("1.67") else a) for a, _ in s["radii"][:3])
            md.append(f"| {name} | {s['top']} | {s['height']} | {s['bg']} | {' '.join(c.split('/')[-1] for c in s['components'])} | {f} | {z} | {r} | {s['smallUppercase']} / {s['textNodes']} | {s['under12px']} | {s['icons']} |")
        md.append("")
md += ["## Animation and decoration inventory (from source)", "", "| File | `motion.*` elements | In-view entrances (`whileInView` / `<Reveal`) | Hover classes (`hover:` / `group-hover:`) | `uppercase` classes | `rounded-full` | Gradients | Icons used |", "| --- | --- | --- | --- | --- | --- | --- | --- |"]
for p in sorted(src.rglob("*.tsx")):
    t = p.read_text()
    icons = re.search(r'import \{([^}]*)\} from "lucide-react"', t, re.S)
    n_icons = len([x for x in icons.group(1).split(",") if x.strip()]) if icons else 0
    n_motion = len(re.findall(r"<motion\.", t)); n_upper = len(re.findall(r"\buppercase\b", t))
    md.append(f"| {p.relative_to(src)} | {n_motion} | {t.count('whileInView') + t.count('<Reveal')} | {t.count('hover:')} | {n_upper} | {t.count('rounded-full')} | {t.count('bg-gradient') + t.count('hero-vignette')} | {n_icons} |")
md += ["", "## Copy, verbatim (innerText at 1440px)", ""]
for route, by_w in cap["routes"].items():
    md += [f"### `{route}`", ""]
    for s in by_w["1440"]:
        if s["tag"] in ("header", "footer") and route != "/":
            continue
        md += [f"#### {(s['id'] or s['heading'] or s['tag']).splitlines()[0][:60] if (s['id'] or s['heading'] or s['tag']) else s['tag']}", "", "```text", s["text"], "```", ""]
(HERE / "inputs/dossier/DOSSIER-generated.md").write_text("\n".join(md))
